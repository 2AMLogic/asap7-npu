#!/usr/bin/env python3
"""Write the PLACEHOLDER Liberty timing views of the npu_sram_bank macro
(decision 0002 option 1) at the SS, TT and FF corners of spec/npu.md.

    python3 -I layout/flow/gen-macro-lib.py [OUT_DIR]

OUT_DIR defaults to layout/macros, where the committed views live; the
pre-route STA runner regenerates into a scratch dir and requires the bytes to
match, the same freshness gate run.sh applies to the LEF. The output is
deterministic: no timestamps, everything derives from
layout/flow/macro-lib-params.json -- except the cell area, which the generator
reads from the committed LEF abstract's SIZE (width x height,
layout/macros/npu_sram_bank.lef), so the Liberty area mirrors the LEF
footprint exactly and the two views cannot drift (issue #89).

RULE lib-anchored-placeholder-v1 (stated once here, in the parameter table,
and in every generated file's header): the macro has no bitcell and was never
characterised, so **every timing number is a placeholder, never a memory
measurement**. Each corner's numbers derive from one committed anchor delay
-- BUFx4_ASAP7_75t_R's cell_rise at a fixed table position of the pinned
asap7sc7p5t_28 RVT decks -- times fixed multipliers: clk->q x10 (a placeholder
read path of decode + sense + mux + out-drive, ten buffer stages at the
library's own speed scale), setup x1, hold x0.2, min_pulse_width x2,
max_transition x4. The anchor delays differ per corner, so the macro tracks
the standard-cell library it is timed beside; pin capacitances are
corner-invariant placeholders. This mirrors, by reference, what the origin
found its analytical macro corners are (sky130-npu#159: algebraic factors on a
baseline, not a re-characterisation) and keeps the spec's requirement that the
rule is stated and the numbers labelled.

Ports and bus widths mirror gen-macro-lef.py and the black box
rtl/pdk/asap7/npu_sram_bank.v (1024 x 32: rw_we[3:0], rw_addr[9:0],
rw_wdata[31:0], rw_rdata[31:0], r_addr[9:0], r_rdata[31:0]); the regression
test cross-checks all three. The timing contract is the black box's: both
ports synchronous, read data launching on the rising clk edge after the
address is captured (timing_type rising_edge), setup/hold on every input
against the same edge, min_pulse_width on clk.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PARAMS = os.path.join(HERE, "macro-lib-params.json")
LEF = os.path.join(HERE, "..", "macros", "npu_sram_bank.lef")

DEPTH_BITS = 10          # $clog2(1024)
inputs = (["clk", "rw_en"] + [f"rw_we[{i}]" for i in range(4)]
          + [f"rw_addr[{i}]" for i in range(DEPTH_BITS)]
          + [f"rw_wdata[{i}]" for i in range(32)]
          + ["r_en"] + [f"r_addr[{i}]" for i in range(DEPTH_BITS)])
outputs = [f"rw_rdata[{i}]" for i in range(32)] + [f"r_rdata[{i}]" for i in range(32)]

RULE_NAME = "lib-anchored-placeholder-v1"


def lef_footprint():
    """The committed LEF abstract's SIZE, as (width, height, area).

    The cell area of every Liberty view is this footprint product, so the
    Liberty area and the LEF abstract cannot drift apart (issue #89; the
    area was once an unsourced literal matching no source). Resolved
    relative to the generator, not the output directory, so regenerating
    into a scratch dir reads the same committed LEF.
    """
    m = re.search(r"SIZE ([\d.]+) BY ([\d.]+) ;", open(LEF).read())
    if not m:
        sys.exit(f"gen-macro-lib.py: no SIZE statement found in {LEF}")
    return m.group(1), m.group(2), float(m.group(1)) * float(m.group(2))


def fmt(v):
    return f"{v:.4f}"


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "macros")
    p = json.load(open(PARAMS))
    rule = p["rule"]
    a = rule["anchor"]
    m = rule["multipliers"]
    anchors = {"SS": a["ss_ns"], "TT": a["tt_ns"], "FF": a["ff_ns"]}
    lef_w, lef_h, area = lef_footprint()

    for corner, c in p["corners"].items():
        anchor = anchors[corner]
        tco = m["tco"] * anchor
        setup = m["setup"] * anchor
        hold = m["hold"] * anchor
        mpw = m["min_pulse_width"] * anchor
        mxt = m["max_transition"] * anchor
        cap_in = rule["pin_capacitance_pf"]["input"]
        cap_clk = rule["pin_capacitance_pf"]["clk"]
        max_cap = rule["output_max_capacitance_pf"]

        out = []
        w = out.append
        w(f"/* npu_sram_bank PLACEHOLDER Liberty timing model, corner {corner}"
          f" ({c['nom_voltage']:.2f} V, {c['nom_temperature']:.0f} C).")
        w(" * GENERATED by layout/flow/gen-macro-lib.py from"
          " layout/flow/macro-lib-params.json; do not edit.")
        w(f" * RULE {RULE_NAME}: every timing number below is a PLACEHOLDER derived")
        w(" * from one committed anchor delay (BUFx4_ASAP7_75t_R cell_rise"
          " index_1[3]/index_2[3]")
        w(f" * of asap7sc7p5t_28 @ {a['library_commit'][:12]}, RVT, at this corner;"
          f" anchors TT {a['tt_ns']:.6f} /")
        w(f" * SS {a['ss_ns']:.6f} / FF {a['ff_ns']:.6f} ns, read {a['read_date']})"
          f" times fixed multipliers")
        w(f" * (clk->q x{m['tco']}, setup x{m['setup']}, hold x{m['hold']},"
          f" min_pulse_width x{m['min_pulse_width']}, max_transition x{m['max_transition']},"
          f" output transition x{m['transition']}).")
        w(" * This is NOT a memory measurement: the macro has no bitcell and was never")
        w(" * characterised (spec/npu.md \"On-chip memory\", decision 0002).")
        w(f" * Cell area {area:.4f} um^2 is the LEF abstract footprint product")
        w(f" * (SIZE {lef_w} BY {lef_h}, layout/macros/npu_sram_bank.lef);")
        w(" * corner-invariant, like the pin capacitances.")
        if corner == "FF":
            w(" * FF is a provisional corner: the standard-cell deck's SIMPLE_RVT_FF")
            w(" * header anomaly (0.7 V / 25 C header in a 0.77 V / 0 C corner,")
            w(" * spec/npu.md PVT corners) makes any FF-corner hold result provisional;")
            w(" * this placeholder view is timed beside that deck and inherits that.")
        w(" * Pin capacitances are corner-invariant placeholders. */")
        w(f"library (npu_sram_bank_{c['suffix']}) {{")
        w("  delay_model : table_lookup ;")
        w('  time_unit : "1ns" ;')
        w('  voltage_unit : "1V" ;')
        w('  current_unit : "1mA" ;')
        w('  pulling_resistance_unit : "1kohm" ;')
        w('  leakage_power_unit : "1nW" ;')
        w("  capacitive_load_unit (1, pf) ;")
        w(f"  nom_voltage : {c['nom_voltage']:.2f} ;")
        w(f"  nom_temperature : {c['nom_temperature']:.1f} ;")
        w(f"  default_max_transition : {fmt(mxt)} ;")
        w("  default_cell_leakage_power : 0 ;")
        w("  lu_table_template (delay_1x1) {")
        w("    variable_1 : total_output_net_capacitance ;")
        w('    index_1 ("1") ;')
        w("  }")
        w("  lu_table_template (constraint_1x1) {")
        w("    variable_1 : constrained_pin_transition ;")
        w("    variable_2 : related_pin_transition ;")
        w('    index_1 ("1") ;')
        w('    index_2 ("1") ;')
        w("  }")
        for name, width in (("B4", 4), ("B10", DEPTH_BITS), ("B32", 32)):
            w(f"  type ({name}) {{ base_type : array ; data_type : bit ;"
              f" bit_width : {width} ; bit_from : {width - 1} ; bit_to : 0 ; }}")
        w("  cell (npu_sram_bank) {")
        w(f"    area : {area:.4f} ;")
        w("    pin (clk) {")
        w("      direction : input ;")
        w("      clock : true ;")
        w(f"      capacitance : {fmt(cap_clk)} ;")
        w(f"      min_pulse_width : {fmt(mpw)} ;")
        w(f"      minimum_period : {fmt(tco + setup)} ;")
        w("    }")

        def in_timing():
            w("      timing () {")
            w('        related_pin : "clk" ;')
            w("        timing_type : setup_rising ;")
            w(f"        rise_constraint (constraint_1x1) {{ values (\"{fmt(setup)}\") }}")
            w(f"        fall_constraint (constraint_1x1) {{ values (\"{fmt(setup)}\") }}")
            w("      }")
            w("      timing () {")
            w('        related_pin : "clk" ;')
            w("        timing_type : hold_rising ;")
            w(f"        rise_constraint (constraint_1x1) {{ values (\"{fmt(hold)}\") }}")
            w(f"        fall_constraint (constraint_1x1) {{ values (\"{fmt(hold)}\") }}")
            w("      }")

        trans = m["transition"] * anchor

        def out_timing():
            w("      timing () {")
            w('        related_pin : "clk" ;')
            w("        timing_type : rising_edge ;")
            w(f"        cell_rise (delay_1x1) {{ values (\"{fmt(tco)}\") }}")
            w(f"        cell_fall (delay_1x1) {{ values (\"{fmt(tco)}\") }}")
            w(f"        rise_transition (delay_1x1) {{ values (\"{fmt(trans)}\") }}")
            w(f"        fall_transition (delay_1x1) {{ values (\"{fmt(trans)}\") }}")
            w("      }")

        buses = {"rw_we": "B4", "rw_addr": "B10", "rw_wdata": "B32",
                 "r_addr": "B10", "rw_rdata": "B32", "r_rdata": "B32"}
        for name in ("rw_en", "r_en"):
            w(f"    pin ({name}) {{")
            w("      direction : input ;")
            w(f"      capacitance : {fmt(cap_in)} ;")
            in_timing()
            w("    }")
        for name in ("rw_we", "rw_addr", "rw_wdata", "r_addr"):
            w(f"    bus ({name}) {{")
            w(f"      bus_type : {buses[name]} ;")
            w("      direction : input ;")
            w(f"      capacitance : {fmt(cap_in)} ;")
            in_timing()
            w("    }")
        for name in ("rw_rdata", "r_rdata"):
            w(f"    bus ({name}) {{")
            w(f"      bus_type : {buses[name]} ;")
            w("      direction : output ;")
            w(f"      max_capacitance : {fmt(max_cap)} ;")
            out_timing()
            w("    }")
        w("  }")
        w("}")
        w("")
        path = os.path.join(out_dir, f"npu_sram_bank_{c['suffix']}.lib")
        with open(path, "w") as f:
            f.write("\n".join(out))
        print(path)


if __name__ == "__main__":
    main()
