#!/usr/bin/env python3
"""Write the abstract LEF for the npu_sram_bank macro (decision 0002 option 1).

    python3 -I layout/flow/gen-macro-lef.py > layout/macros/npu_sram_bank.lef

`klt lef-abstract` derives a LEF from a block layout plus a socket descriptor;
the memory macro has no layout (no bitcell, decision 0002), so this generator
writes the MACRO/PIN/OBS text directly from the parameters below. The output is
deterministic. It is an abstract view only: the footprint and pin positions are
a stated rule (decision 0005), not a memory design.

Footprint rule (decision 0005): area = bits * (747.5 um^2 / 16384 bits), the
density of the upstream `srambank_64x4x64_6t122` reference (9.612 x 77.76 um,
64*4*64 bits), rounded up to whole placement sites (0.054 um) and rows
(0.27 um). A 1024 x 32 bank is 32768 bits.
"""
import math

SITE_W, ROW_H = 0.054, 0.27
M3_PITCH = 0.036           # M3, vertical: signal pins are vertical stubs on M3
M5_PITCH = 0.048           # M5, vertical: power stripes (the PDN strap layer they connect to)
BITS = 1024 * 32
REF_AREA_UM2, REF_BITS = 9.612 * 77.76, 64 * 4 * 64
ASPECT = 0.6                # width / height

area = BITS * REF_AREA_UM2 / REF_BITS
h = math.sqrt(area / ASPECT)
rows = math.ceil(h / ROW_H)
sites = math.ceil(area / (rows * ROW_H) / SITE_W)
W, H = round(sites * SITE_W, 3), round(rows * ROW_H, 3)

STUB = 0.576               # signal-pin stub length along y (also the OBS-free strip on M2-M4)
PIN_PITCH = 8 * M3_PITCH   # signal pin pitch on the edge
PIN_X0 = 4 * PIN_PITCH     # first pin x, clear of the corner
PW = 0.018                 # M3 minimum width
PG_W = 0.12                # M5 width-table entry
PG_STEP = 12 * M5_PITCH    # VDD-to-VSS centre distance
PG_X0 = 10 * M5_PITCH      # first stripe centre, clear of the left edge

DEPTH_BITS = 10
inputs = (["clk", "rw_en"] + [f"rw_we[{i}]" for i in range(4)]
          + [f"rw_addr[{i}]" for i in range(DEPTH_BITS)]
          + [f"rw_wdata[{i}]" for i in range(32)]
          + ["r_en"] + [f"r_addr[{i}]" for i in range(DEPTH_BITS)])
outputs = ([f"rw_rdata[{i}]" for i in range(32)] + [f"r_rdata[{i}]" for i in range(32)])


def f(v):
    return f"{v:.3f}"


out = []
w = out.append
w("# npu_sram_bank abstract LEF. GENERATED by layout/flow/gen-macro-lef.py; do not edit.")
w("# Abstract view only (MACRO/PIN/OBS): no internal layout, no bitcell. Footprint rule: decision 0005.")
w("VERSION 5.8 ;")
w('BUSBITCHARS "[]" ;')
w('DIVIDERCHAR "/" ;')
w("")
w("MACRO npu_sram_bank")
w("  CLASS BLOCK ;")
w("  ORIGIN 0 0 ;")
w(f"  FOREIGN npu_sram_bank 0 0 ;")
w(f"  SIZE {f(W)} BY {f(H)} ;")
w("  SYMMETRY X Y ;")


def pin(name, direction, x, y0, y1):
    xl, xr = x - PW / 2, x + PW / 2
    w(f"  PIN {name}")
    w(f"    DIRECTION {direction} ;")
    w("    USE SIGNAL ;")
    w("    PORT")
    w("      LAYER M3 ;")
    w(f"        RECT {f(xl)} {f(y0)} {f(xr)} {f(y1)} ;")
    w("    END")
    w(f"  END {name}")


for i, n in enumerate(inputs):
    pin(n, "INPUT", PIN_X0 + i * PIN_PITCH, 0.0, STUB)
for i, n in enumerate(outputs):
    pin(n, "OUTPUT", PIN_X0 + i * PIN_PITCH, H - STUB, H)

stripes = {"VDD": [], "VSS": []}
x, k = PG_X0, 0
while x + PG_W / 2 < W - 0.4:
    stripes["VDD" if k % 2 == 0 else "VSS"].append(x)
    x += PG_STEP
    k += 1
for net, use in (("VDD", "POWER"), ("VSS", "GROUND")):
    w(f"  PIN {net}")
    w("    DIRECTION INOUT ;")
    w(f"    USE {use} ;")
    w("    PORT")
    w("      LAYER M5 ;")
    for xc in stripes[net]:
        w(f"        RECT {f(xc - PG_W / 2)} 0.500 {f(xc + PG_W / 2)} {f(H - 0.5)} ;")
    w("    END")
    w(f"  END {net}")

w("  OBS")
w("    LAYER M1 ;")
w(f"      RECT 0.000 0.000 {f(W)} {f(H)} ;")
for layer in ("M2", "M3", "M4"):
    w(f"    LAYER {layer} ;")
    w(f"      RECT 0.000 {f(STUB)} {f(W)} {f(H - STUB)} ;")
w("    LAYER M5 ;")
w(f"      RECT 0.000 0.000 {f(W)} {f(H)} ;")
w("  END")
w("END npu_sram_bank")
w("")
w("END LIBRARY")
print("\n".join(out))
