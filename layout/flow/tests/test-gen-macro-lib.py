#!/usr/bin/env python3
"""Regression tests for layout/flow/gen-macro-lib.py and its committed outputs.

    python3 -I layout/flow/tests/test-gen-macro-lib.py

Plain asserts, standard library only -- the same no-harness convention as
test-prep-netlist.py. Run by .github/workflows/flow-tests.yml.

What is pinned, and why each case exists:

1. Regenerating the three Liberty views reproduces the committed bytes. This
   is the STA runner's freshness gate; pinning it here means a generator edit
   that changes any output byte fails CI before the runner ever runs.
2. Pin and bus names match the LEF abstract and the black box exactly. The
   three views of the macro (LEF, Liberty, Verilog seam) are written by three
   files; if their port lists drift, OpenSTA silently times the wrong pins or
   fails at link, naming the engine rather than the drift.
3. Every view is labelled PLACEHOLDER with its rule and states it is not a
   memory measurement -- spec/npu.md requires the label on every timing
   number the macro contributes.
4. The corner numbers obey the stated rule: each corner's clk->q equals its
   committed anchor delay times the committed tco multiplier, so a regenerated
   anchor cannot quietly desynchronise the three corners.
5. nom_voltage / nom_temperature equal the spec/npu.md PVT rows, and the FF
   view's header names the SIMPLE_RVT_FF anomaly context (the macro view is a
   placeholder at every corner; the anomaly concerns the standard-cell deck).
6. Every view's cell area equals the committed LEF abstract's SIZE product,
   computed here from the LEF independently of the generator (issue #89: the
   area was once an unsourced literal matching neither the LEF footprint nor
   decision 0002's rule, and nothing caught it). The parameter table carries
   no independent area literal to drift back to.

No PDK, tool or network is touched: the anchors are committed constants, and
the generator is pure Python over the parameter table.
"""
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
FLOW = os.path.dirname(HERE)
REPO = os.path.dirname(os.path.dirname(FLOW))
GEN = os.path.join(FLOW, "gen-macro-lib.py")
PARAMS = json.load(open(os.path.join(FLOW, "macro-lib-params.json")))
LEF = os.path.join(REPO, "layout", "macros", "npu_sram_bank.lef")
BB = os.path.join(REPO, "rtl", "pdk", "asap7", "npu_sram_bank.v")
LIBS = {c: os.path.join(REPO, "layout", "macros", f"npu_sram_bank_{v['suffix']}.lib")
        for c, v in PARAMS["corners"].items()}

failures = []


def check(name, cond, detail=""):
    if cond:
        print(f"ok: {name}")
    else:
        failures.append(name)
        print(f"FAIL: {name} {detail}")


# 1. regeneration reproduces the committed bytes
with tempfile.TemporaryDirectory() as tmp:
    subprocess.run([sys.executable, "-I", GEN, tmp], check=True, capture_output=True)
    for corner, path in LIBS.items():
        want = open(path, "rb").read()
        got = open(os.path.join(tmp, os.path.basename(path)), "rb").read()
        check(f"{os.path.basename(path)} regenerates byte-identically", want == got,
              f"{len(want)} committed vs {len(got)} regenerated bytes")

# 2. pin/bus names match the LEF and the black box
lef_pins = set(re.findall(r"^  PIN (\S+)", open(LEF).read(), re.M)) - {"VDD", "VSS"}
# $clog2(1024) = 10, WORD_BITS/8 = 4: the black box's parameters resolve to these widths
widths = {"clk": 1, "rw_en": 1, "rw_we": 4, "rw_addr": 10, "rw_wdata": 32,
          "rw_rdata": 32, "r_en": 1, "r_addr": 10, "r_rdata": 32}
bb_ports = set()
for m in re.finditer(r"^\s*(input|output)\s+wire\s*(?:\[[^]]*\])?\s*(\w+)\s*[),\n]",
                     open(BB).read(), re.M):
    name = m.group(2)
    bb_ports |= {name} if widths[name] == 1 else {f"{name}[{i}]" for i in range(widths[name])}
check("LEF signal pins equal black-box ports", lef_pins == bb_ports,
      f"only-in-LEF {sorted(lef_pins - bb_ports)}, only-in-bb {sorted(bb_ports - lef_pins)}")

lib_types = {}
bus_widths = {}
for corner, path in LIBS.items():
    text = open(path).read()
    for m in re.finditer(r"type \((\w+)\) \{[^}]*bit_width : (\d+) ;", text):
        lib_types[m.group(1)] = int(m.group(2))
    names = set(re.findall(r"^    (?:pin|bus) \((\w+)\)", text, re.M))
    for m in re.finditer(r"bus \((\w+)\) \{\s*bus_type : (\w+) ;", text):
        bus_widths[m.group(1)] = lib_types[m.group(2)]
    lib_pins = set()
    for n in names:
        lib_pins |= {n} if n not in bus_widths else {f"{n}[{i}]" for i in range(bus_widths[n])}
    check(f"{os.path.basename(path)} pins equal the LEF signal pins", lib_pins == lef_pins,
          f"only-in-lib {sorted(lib_pins - lef_pins)}, only-in-LEF {sorted(lef_pins - lib_pins)}")

# 3. placeholder labelling and rule
for corner, path in LIBS.items():
    head = "\n".join(open(path).read().splitlines()[:16])
    check(f"{os.path.basename(path)} is labelled PLACEHOLDER with its rule",
          "PLACEHOLDER" in head and "GENERATED by layout/flow/gen-macro-lib.py" in head
          and "NOT a memory measurement" in head and "RULE" in head, head)

# 4. the corner numbers obey the stated rule
a, m = PARAMS["rule"]["anchor"], PARAMS["rule"]["multipliers"]
for corner, path in LIBS.items():
    text = open(path).read()
    tco = float(re.search(r"cell_rise \(delay_1x1\) \{ values \(\"([\d.]+)\"\) \}", text).group(1))
    want = m["tco"] * a[f"{corner.lower()}_ns"]
    check(f"{os.path.basename(path)} clk->q equals anchor x tco multiplier",
          abs(tco - want) < 5e-4, f"{tco} vs {want}")

# 5. PVT rows match spec/npu.md; the FF anomaly is named in the FF view
pvt = {"SS": (0.63, 100), "TT": (0.70, 25), "FF": (0.77, 0)}
for corner, path in LIBS.items():
    text = open(path).read()
    v = float(re.search(r"nom_voltage : ([\d.]+) ;", text).group(1))
    t = float(re.search(r"nom_temperature : ([\d.]+) ;", text).group(1))
    check(f"{os.path.basename(path)} PVT is the spec row for {corner}",
          (v, t) == pvt[corner], f"{v} V / {t} C vs {pvt[corner]}")
ff_head = "\n".join(open(LIBS["FF"]).read().splitlines()[:20])
check("FF view header names the SIMPLE_RVT_FF anomaly context",
      "SIMPLE_RVT_FF" in ff_head, ff_head)

# 6. the cell area is the LEF footprint product at every corner, computed
#    here from the LEF itself, independent of the generator's derivation
m = re.search(r"SIZE ([\d.]+) BY ([\d.]+) ;", open(LEF).read())
lef_area = float(m.group(1)) * float(m.group(2))
check("macro-lib-params.json carries no independent area literal",
      "area_um2" not in PARAMS, "area_um2 present; the area must derive from the LEF SIZE")
for corner, path in LIBS.items():
    text = open(path).read()
    area = float(re.search(r"^\s+area : ([\d.]+) ;", text, re.M).group(1))
    check(f"{os.path.basename(path)} area equals the LEF SIZE product",
          abs(area - lef_area) <= 5e-5, f"{area} vs LEF {m.group(1)} x {m.group(2)} = {lef_area}")

if failures:
    print(f"{len(failures)} failure(s): {failures}")
    sys.exit(1)
print("all gen-macro-lib tests passed")
